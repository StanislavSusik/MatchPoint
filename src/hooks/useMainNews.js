export function useMainNews(dateStr) {
  const [newsData, setNewsData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let isMounted = true;
    setLoading(true);

    const timer = setTimeout(() => {
      if (isMounted) {
        setNewsData(MOCK_NEWS_BY_DATE[dateStr] || null);
        setLoading(false);
      }
    }, 400);

    return () => {
      isMounted = false;
      clearTimeout(timer);
    };
  }, [dateStr]);

  return { newsData, loading };
}